"""Writes apps/web/src/styles/tokens.css from the Hush design tokens.

Usage: python3 scripts/design/gen-tokens.py
(reads scripts/design/hush-tokens.json, the design system's tokens.json)
"""
import json,os,sys
ROOT=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC=os.path.join(ROOT,'scripts','design','hush-tokens.json')
OUT=os.path.join(ROOT,'apps','web','src','styles','tokens.css')
t=json.load(open(SRC))
def val(v,th):
    if isinstance(v,dict): v=v[th]
    if isinstance(v,str) and v.startswith('{') and v.endswith('}'): return f"var(--{v[1:-1]})"
    return v
colors=t['color']['tokens']; shadows=t['shadow']['tokens']
out=['/* Generated by scripts/design/gen-tokens.py from scripts/design/hush-tokens.json (the Hush design system). Edit those, not this file. */','',':root {']
for k,v in t['type']['families'].items(): out.append(f"  --font-{k}: {v};")
for g in t['type']['groups']:
    for s in g['styles']:
        out.append(f"  --t-{s['name']}: {s['fontWeight']} {s['fontSize']}/{s['lineHeight']} var(--font-{g['family']});")
        if s.get('letterSpacing'): out.append(f"  --t-{s['name']}-tracking: {s['letterSpacing']};")
for grp in ('spacing','radius','duration','easing','zIndex'):
    for tok in t[grp]['tokens']: out.append(f"  --{tok['name']}: {tok['value']};")
out.append('}')
# Dusk is the dark theme and the call stage's material in both themes.
for th,sel in (('dusk',":root,\n[data-theme='dark'],\n[data-theme='light'] .media-stage"),('mist',"[data-theme='light']")):
    out+=['',sel+' {', f"  color-scheme: {'dark' if th=='dusk' else 'light'};"]
    for c in colors: out.append(f"  --{c['name']}: {val(c['value'],th)};")
    for s in shadows: out.append(f"  --{s['name']}: {val(s['value'],th)};")
    out.append('}')
out+=['','@media (prefers-reduced-motion: reduce) {','  :root {','    --dur-base: 0ms;','    --dur-slow: 0ms;','    --dur-signature: 0ms;','    --dur-ambient: 0ms;','  }','}']
open(OUT,'w').write('\n'.join(out)+'\n')
